"""Pack generated PRL NPC artwork without drawing or recolouring characters.

Sources are transparent 4-column, 2-row atlases. The mother uses all eight
cells as one walk cycle; the others have separate walk/hurry rows. Keep a
shared scale per character and ground every frame at the same foot baseline.
"""
import base64
import json
from pathlib import Path
from statistics import median

from PIL import Image

ROOT = Path(__file__).resolve().parent
ASSETS = ROOT / 'assets' / 'pedestrians'
PROFILES = {
    'elderly': {'width': 48, 'height': 43, 'anchor': 24},
    'mother': {'width': 88, 'height': 46, 'anchor': 24},
    'blonde': {'width': 48, 'height': 47, 'anchor': 24},
}


def build():
    data = {}
    for name, profile in PROFILES.items():
        source_name = 'mother-walk-v2-source.png' if name == 'mother' else f'{name}-source.png'
        source = Image.open(ASSETS / source_name).convert('RGBA')
        cells = []
        for row in range(2):
            for col in range(4):
                cell = source.crop((col * source.width // 4, row * source.height // 2,
                                    (col + 1) * source.width // 4, (row + 1) * source.height // 2))
                bounds = cell.getchannel('A').point(lambda a: 255 if a > 24 else 0).getbbox()
                if not bounds:
                    raise ValueError(f'Empty {name} frame: {row}, {col}')
                cells.append(cell.crop(bounds))
        width = profile['width']
        scale = min(profile['height'] / median(cell.height for cell in cells[:4]),
                    (width - 4) / max(cell.width for cell in cells),
                    49 / max(cell.height for cell in cells))
        columns = 8 if name == 'mother' else 4
        rows = 1 if name == 'mother' else 2
        sheet = Image.new('RGBA', (width * columns, 56 * rows))
        for i, cell in enumerate(cells):
            small = cell.resize((max(1, round(cell.width * scale)),
                                 max(1, round(cell.height * scale))), Image.Resampling.LANCZOS)
            # The right edge belongs to the rigid pram, regardless of stride.
            # Anchoring the left silhouette would shift the pram as feet swing.
            left = 64 - small.width if name == 'mother' else (width - small.width) // 2
            sheet.alpha_composite(small, ((i % columns) * width + left,
                                         (i // columns) * 56 + 51 - small.height))
        path = ASSETS / f'{name}-sprites.png'
        sheet.save(path, optimize=True)
        data[name] = {
            'frameWidth': width, 'frameHeight': 56, 'frames': columns, 'rows': rows,
            'anchorX': profile['anchor'], 'footY': 51,
            'sheet': 'data:image/png;base64,' + base64.b64encode(path.read_bytes()).decode('ascii'),
        }
        if name == 'mother':
            data[name].update(pramStartX=34, pramLowerStartX=40, pramSplitY=38, pramFrame=2)
        print(f'Packed {name}: {path.relative_to(ROOT)}')
    (ROOT / 'prl_pedestrian_assets.js').write_text(
        '/* Generated by build_prl_pedestrian_assets.py; original artwork in assets/pedestrians/. */\n'
        'globalThis.PRL_PEDESTRIAN_ASSETS = ' + json.dumps(data) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    build()
